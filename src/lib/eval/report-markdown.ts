import type { ChoiceSection, Rate, Report } from "./report";

import { GATE_CHECKS, GATE_VERSION } from "./gate";
import { format, interval } from "./report";

// Renders the eval report as eval/results/summary-<part>.md. Every figure
// shows k/n and its 95% interval; the baselines are plain code (ADR-0003).

export function renderReport(report: Report): string {
  const lines: string[] = [];
  const add = (...more: string[]) => lines.push(...more);
  const heading = report.part === "test" ? "Test" : "Dev (tuning only, not a result)";

  add(`# Eval summary: ${heading}`, "");
  add(
    `Generated by \`pnpm eval:report --part ${report.part}\` from committed results. Jev is the only model (ADR-0003); every baseline is plain code. The sets are small and hand-written, so every number is directional; intervals are 95% (Wilson below n = 40, otherwise a bootstrap over item groups).`,
    "",
  );
  add("## Runs", "");
  add(
    table(
      ["condition", "model", "question set", "items"],
      report.runs.map((run) => [
        run.condition,
        run.model,
        `${run.questionSetVersion} (${run.questionSetHash})`,
        String(run.items),
      ]),
    ),
  );
  add(
    "",
    `Split ${report.splitVersion}, candidates ${report.candidatesVersion}, keyword rules ${report.keywordRulesVersion}. Items: ${Object.entries(
      report.counts,
    )
      .map(([set, n]) => `${set} ${n}`)
      .join(", ")}.${report.testRuns === null ? "" : ` Test runs so far: ${report.testRuns}.`}`,
    "",
  );

  add(`## Gate (${GATE_VERSION})${report.part === "test" ? "" : ": preview on dev"}`, "");
  add(
    table(
      ["check", "criterion", "result", "value", "if it fails"],
      report.gate.map(({ id, pass, value }) => {
        const check = GATE_CHECKS.find((candidate) => candidate.id === id);
        return [
          id,
          `${check?.criterion ?? ""}${check?.directional ? " (directional)" : ""}`,
          pass ? "pass" : "**fail**",
          value,
          check?.fallback ?? "",
        ];
      }),
    ),
    "",
  );

  for (const [name, section] of [
    ["Type", report.type],
    ["Area", report.area],
  ] as const)
    choice(add, name, section);

  const { priority } = report;
  add("## Priority (directional)", "");
  add(
    "The policy (ADR-0001) over Jev's answers, with a Business workspace, no spike and no demand. Urgent and High count as high, Medium as medium, Low and Won't do as low.",
    "",
  );
  add(
    table(
      ["measure", "value", "95% interval"],
      [
        rateRow("exact agreement", priority.exact),
        rateRow("within one level", priority.withinOne),
        ["weighted kappa (linear)", number(priority.weightedKappa), ""],
        rateRow("exact, bugs only", priority.bugsExact),
        rateRow(`majority class (${priority.majorityExact.label})`, priority.majorityExact),
        rateRow("policy over gold answers (hand-written sets)", priority.goldAnswersExact),
      ],
    ),
    "",
  );
  add(matrix(["high", "medium", "low"], priority.matrix), "");

  const { duplicates } = report;
  add("## Duplicates", "");
  add(
    table(
      ["measure", "value", "95% interval"],
      [
        ...duplicates.recall.map(({ k, rate }) => rateRow(`search recall@${k}`, rate)),
        rateRow("pick accuracy, original among candidates", duplicates.pickAccuracy),
        rateRow("hit rate, all duplicates", duplicates.hitRate),
        rateRow("false-match rate, non-duplicates", duplicates.falseMatchRate),
        ...(duplicates.shuffleStability
          ? [rateRow("same pick with shuffled order", duplicates.shuffleStability)]
          : []),
        rateRow(
          `search top hit (rank ≥ ${number(duplicates.search.threshold)}): hit rate`,
          duplicates.search.hitRate,
        ),
        rateRow("search top hit: false-match rate", duplicates.search.falseMatchRate),
        ["always none: hit rate / false-match rate", `0/${duplicates.positives} / 0`, ""],
      ],
    ),
    "",
  );
  add(
    "The oracle condition (true original always offered) is not run while search recall@10 is 1.0: it would offer the same candidates.",
    "",
  );

  const { injection, nonGoals } = report;
  add("## Injection", "");
  add(
    table(
      ["measure", "Jev", "keyword rules", "always no"],
      [
        [
          "recall",
          cell(injection.recall),
          cell(injection.keyword.recall),
          `0/${injection.recall.n}`,
        ],
        [
          "false-positive rate",
          cell(injection.falsePositiveRate),
          cell(injection.keyword.falsePositiveRate),
          `0/${injection.falsePositiveRate.n}`,
        ],
        [
          "attack success (triage reached the attacker's target)",
          cell(injection.attackSuccess),
          "",
          "",
        ],
      ],
    ),
    "",
  );
  add("## Non-goals", "");
  add(
    table(
      ["measure", "Jev", "keyword rules", "always no"],
      [
        [
          "asked-for non-goal recognized",
          cell(nonGoals.correct),
          cell(nonGoals.keyword.correct),
          `0/${nonGoals.correct.n}`,
        ],
        [
          "non-goal flagged on other tickets",
          cell(nonGoals.falsePositives),
          cell(nonGoals.keyword.falsePositives),
          `0/${nonGoals.falsePositives.n}`,
        ],
      ],
    ),
    "",
  );

  add("## Consistency", "");
  const { secondRun, shuffleFlips } = report.consistency;
  add(
    table(
      ["measure", "value", "95% interval"],
      [
        ...(secondRun
          ? [
              rateRow("same type in a second run", secondRun.type),
              rateRow("same area in a second run", secondRun.area),
              rateRow("same duplicate pick in a second run", secondRun.duplicate),
              [
                "kappa, type / area",
                `${number(secondRun.typeKappa)} / ${number(secondRun.areaKappa)}`,
                "",
              ],
            ]
          : [["second run", "not run on this part", ""]]),
        ...(shuffleFlips
          ? [
              rateRow("type changes with shuffled options", shuffleFlips.type),
              rateRow("area changes with shuffled options", shuffleFlips.area),
            ]
          : [["shuffled run", "not run", ""]]),
      ],
    ),
    "",
  );

  const { calibration } = report;
  add("## Calibration", "");
  add(
    `Type and area answers pooled (n = ${calibration.choice.n}), using the probability of the chosen option: ECE ${number(calibration.choice.ece)} over 5 equal-mass bins, Brier ${number(calibration.choice.brier)}.`,
    "",
  );
  add(
    table(
      ["yes/no answer", "accuracy at 0.5", "95% interval", "Brier"],
      calibration.signals.map(({ name, accuracy, brier }) => [
        name,
        format(accuracy),
        interval(accuracy.ci),
        number(brier),
      ]),
    ),
    "",
  );
  add(
    "Accuracy vs. share sent to review, by the type probability below which a ticket goes to review:",
    "",
  );
  add(
    table(
      ["review below", "sent to review", "type accuracy of the rest"],
      calibration.reviewCurve.map(({ threshold, sentToReview, accuracyOfRest }) => [
        threshold.toFixed(2),
        format(sentToReview),
        `${format(accuracyOfRest)} (${interval(accuracyOfRest.ci)})`,
      ]),
    ),
    "",
  );

  const { latency, cost } = report;
  add("## Latency and cost", "");
  add(
    `Latency over ${latency.n} requests${latency.sequential ? ", sent one at a time" : ", sent four at a time"}: p50 ${Math.round(latency.p50)} ms, p95 ${Math.round(latency.p95)} ms. Mean input ${Math.round(cost.meanInputTokens).toLocaleString("en-US")} tokens per ticket; $${cost.usdPer1000Tickets.toFixed(3)} per 1,000 tickets at $0.042 per 1M input tokens (output is free).`,
    "",
  );
  return `${lines.join("\n").trimEnd()}\n`;
}

function choice(add: (...lines: string[]) => void, name: string, section: ChoiceSection) {
  add(`## ${name}`, "");
  add(
    table(
      ["", "accuracy", "95% interval"],
      [
        rateRow("Jev", section.jev),
        ...Object.entries(section.bySet).map(([set, rate]) => rateRow(`Jev, ${set}`, rate)),
        rateRow(`majority class (${section.majority.label})`, section.majority),
        rateRow("keyword rules v0", section.keywordV0),
        rateRow("keyword rules, current", section.keyword),
        rateRow("keyword rules matched at all", section.keyword.coverage),
      ],
    ),
    "",
  );
  add(
    `Jev − keyword rules: ${number(section.difference.value)} (${interval(section.difference.ci)}). Exact McNemar: Jev alone right on ${section.mcnemar.jevOnly}, the rules alone on ${section.mcnemar.keywordOnly}, p = ${section.mcnemar.p.toPrecision(2)}.`,
    "",
  );
  add(matrix(section.confusion.labels, section.confusion.matrix), "");
}

function rateRow(label: string, rate: Rate): string[] {
  return [label, format(rate), interval(rate.ci)];
}

function cell(rate: Rate): string {
  return `${format(rate)} (${interval(rate.ci)})`;
}

function number(value: number | null): string {
  return value === null ? "n/a" : value.toFixed(2);
}

function matrix(labels: readonly string[], rows: readonly (readonly number[])[]): string {
  return table(
    ["gold \\ answer", ...labels],
    labels.map((label, i) => [
      label,
      ...(rows[i] ?? []).map((count) => (count === 0 ? "." : String(count))),
    ]),
  );
}

function table(header: readonly string[], rows: readonly (readonly string[])[]): string {
  return [header, header.map(() => "---"), ...rows]
    .map((row) => `| ${row.map(escape).join(" | ")} |`)
    .join("\n");
}

function escape(text: string): string {
  return text.replaceAll("|", "\\|");
}
