import { readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import { z } from "zod";

import type { Report } from "@/lib/eval/report";

import {
  readmeResults,
  renderReadmeResults,
  replaceReadmeResults,
} from "@/lib/eval/readme-results";

// The README's results come from the committed test report (plan M6), so the
// README can't claim a number the eval didn't produce.

const root = join(import.meta.dirname, "../..");
const readme = readFileSync(join(root, "README.md"), "utf8");
// Written by `pnpm eval:report`, so only the shape this test reads is checked.
const report = z
  .custom<Report>((value) => typeof value === "object" && value !== null && "gate" in value)
  .parse(JSON.parse(readFileSync(join(root, "eval/results/report-test.json"), "utf8")));

describe("the README's results", () => {
  it("are exactly what the committed test report renders", () => {
    // If this fails, run `pnpm eval:report --part test`, which rewrites the section.
    expect(readmeResults(readme)).toBe(renderReadmeResults(report));
  });

  it("quote the summary's figures and the failed gate check", () => {
    const section = readmeResults(readme) ?? "";
    const summary = readFileSync(join(root, "eval/results/summary-test.md"), "utf8");

    for (const figure of [
      "116/120 = 0.97",
      "0.93–0.99",
      "107/120 = 0.89",
      "26/26 = 1.00",
      "0/92 = 0.00",
    ]) {
      expect(summary).toContain(figure);
      expect(section).toContain(figure);
    }
    expect(section).toContain("Does Jev find the area clearly better than the keyword rules?");
  });

  it("replace only the marked section", () => {
    const before =
      "# Title\n\n<!-- results:start: generated by `pnpm eval:report --part test`; do not edit by hand -->\nold\n<!-- results:end -->\n\nAfter.\n";

    const after = replaceReadmeResults(before, report);

    expect(after.startsWith("# Title\n\n")).toBe(true);
    expect(after.endsWith("\n\nAfter.\n")).toBe(true);
    expect(readmeResults(after)).toBe(renderReadmeResults(report));
    expect(() => replaceReadmeResults("# No markers\n", report)).toThrow(/no results markers/);
  });
});
